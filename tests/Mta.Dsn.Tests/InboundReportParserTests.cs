using System.Text;
using Mta.Core;
using Mta.Dsn;

namespace Mta.Dsn.Tests;

public class InboundReportParserTests
{
    private static readonly DateTimeOffset Now = new(2026, 10, 12, 8, 0, 0, TimeSpan.Zero);

    private static byte[] Bytes(string s) => Encoding.UTF8.GetBytes(s.Replace("\r\n", "\n").Replace("\n", "\r\n"));

    [Fact]
    public void Our_own_dsn_builder_output_round_trips()
    {
        byte[] original = Bytes("From: sender@example.org\nTo: rcpt@dest.example\nSubject: Hello\nMessage-ID: <abc@example.org>\n\nBody\n");
        byte[] dsn = DsnBuilder.Build(new DsnRequest
        {
            ReportingMta = "mx.eggmail.test", To = EmailAddress.Parse("sender@example.org"), Action = DsnAction.Failed,
            ArrivalDate = Now, Now = Now, OriginalMessage = original, UniqueToken = "t",
            Recipients = [new DsnRecipient(EmailAddress.Parse("rcpt@dest.example"), "5.1.1", "550 5.1.1 User unknown", "mx.dest.example")],
        });
        var report = InboundReportParser.Parse(dsn);
        Assert.Equal(InboundReportKind.DeliveryStatus, report.Kind);
        Assert.Equal("mx.eggmail.test", report.ReportingMta);
        Assert.Equal("<abc@example.org>", report.OriginalMessageId);
        var r = Assert.Single(report.Recipients);
        Assert.Equal("rcpt@dest.example", r.FinalRecipient);
        Assert.Equal("failed", r.Action);
        Assert.Equal("5.1.1", r.Status);
        Assert.True(r.IsPermanentFailure);
        Assert.Contains("User unknown", r.DiagnosticCode);
        Assert.True(report.IsAutoGenerated);
    }

    [Fact]
    public void Postfix_style_dsn_with_folded_fields_and_multiple_recipients()
    {
        string raw = """
            From: MAILER-DAEMON@remote.example
            To: bounce@eggmail.test
            Subject: Undelivered Mail Returned to Sender
            Auto-Submitted: auto-replied
            Content-Type: multipart/report; report-type=delivery-status; boundary="BB"

            --BB
            Content-Type: text/plain

            Could not deliver.
            --BB
            Content-Type: message/delivery-status

            Reporting-MTA: dns; remote.example
            Arrival-Date: Mon, 12 Oct 2026 08:00:00 +0000

            Final-Recipient: rfc822; a@dest.example
            Original-Recipient: rfc822;a@dest.example
            Action: failed
            Status: 5.2.2
            Diagnostic-Code: smtp; 552 5.2.2 mailbox
             full

            Final-Recipient: rfc822; b@dest.example
            Action: delayed
            Status: 4.4.1
            Will-Retry-Until: Tue, 13 Oct 2026 08:00:00 +0000
            --BB
            Content-Type: text/rfc822-headers

            Message-ID: <orig@eggmail.test>
            Subject: x

            --BB--
            """;
        var report = InboundReportParser.Parse(Bytes(raw));
        Assert.Equal(2, report.Recipients.Count);
        Assert.Equal("<orig@eggmail.test>", report.OriginalMessageId);
        Assert.Equal("552 5.2.2 mailbox full", report.Recipients[0].DiagnosticCode);
        Assert.Equal("a@dest.example", report.Recipients[0].OriginalRecipient);
        Assert.True(report.Recipients[1].IsDelay);
        Assert.False(report.Recipients[1].IsPermanentFailure);
    }

    [Fact]
    public void Arf_complaint_is_recognised()
    {
        string raw = """
            From: fbl@isp.example
            To: bounce@eggmail.test
            Subject: FW: spam
            Content-Type: multipart/report; report-type=feedback-report; boundary="FF"

            --FF
            Content-Type: text/plain

            This is an abuse report.
            --FF
            Content-Type: message/feedback-report

            Feedback-Type: abuse
            User-Agent: SomeISP/1.0
            Version: 1
            Original-Rcpt-To: <victim@isp.example>
            Source-IP: 192.0.2.10
            --FF
            Content-Type: message/rfc822

            From: news@example.com
            Message-ID: <m1@eggmail.test>
            Subject: Offer

            body
            --FF--
            """;
        var report = InboundReportParser.Parse(Bytes(raw));
        Assert.Equal(InboundReportKind.FeedbackReport, report.Kind);
        Assert.Equal("abuse", report.FeedbackType);
        Assert.Equal("victim@isp.example", report.ArfOriginalRecipient);
        Assert.Equal("192.0.2.10", report.ArfSourceIp);
        Assert.Equal("<m1@eggmail.test>", report.OriginalMessageId);
    }

    [Theory]
    [InlineData("")]
    [InlineData("garbage without headers")]
    [InlineData("Subject: out of office\n\nI am away.\n")]
    [InlineData("Content-Type: multipart/report; report-type=delivery-status; boundary=\"x\"\n\n--x\nContent-Type: text/plain\n\nno status part\n--x--\n")]
    [InlineData("Content-Type: multipart/report; report-type=other; boundary=\"x\"\n\n--x--\n")]
    public void Anything_else_is_unrecognized(string raw)
    {
        var report = InboundReportParser.Parse(Bytes(raw));
        Assert.Equal(InboundReportKind.Unrecognized, report.Kind);
        Assert.Empty(report.Recipients);
    }

    [Fact]
    public void Hostile_fields_are_sanitised_and_bounded()
    {
        string many = string.Concat(Enumerable.Range(0, 300).Select(i => $"Final-Recipient: rfc822; u{i}@x.example\nAction: failed\nStatus: 5.1.1\n\n"));
        string raw = "Content-Type: multipart/report; report-type=delivery-status; boundary=\"B\"\n\n--B\nContent-Type: message/delivery-status\n\nReporting-MTA: dns; m\n\n"
            + many + "--B--\n";
        var report = InboundReportParser.Parse(Bytes(raw));
        Assert.Equal(100, report.Recipients.Count);

        string bad = "Content-Type: multipart/report; report-type=delivery-status; boundary=\"B\"\n\n--B\nContent-Type: message/delivery-status\n\nReporting-MTA: dns; m\n\nFinal-Recipient: rfc822; a@x.example\nAction: failed\nStatus: 9.9.9\nDiagnostic-Code: smtp; \u0007bell " + new string('x', 5000) + "\n--B--\n";
        var r = Assert.Single(InboundReportParser.Parse(Bytes(bad)).Recipients);
        Assert.Null(r.Status);
        Assert.False(r.IsPermanentFailure);
        Assert.True(r.DiagnosticCode!.Length <= 1024);
        Assert.DoesNotContain('\u0007', r.DiagnosticCode);
    }

    [Fact]
    public void Control_characters_in_every_extracted_field_are_removed()
    {
        // Found by the fuzzer: a lone CR survives the line splitting and used to reach Action, Final-Recipient, Remote-MTA and Reporting-MTA.
        string raw = "Content-Type: multipart/report; report-type=delivery-status; boundary=\"B\"\n\n--B\nContent-Type: message/delivery-status\n\n"
            + "Reporting-MTA: dns; mx\rinjected\n\n"
            + "Final-Recipient: rfc822; a\r@x.example\nOriginal-Recipient: rfc822; o\u0001@x.example\nAction: fa\riled\nStatus: 5.1.1\nRemote-MTA: dns; r\u007f.example\n--B--\n";
        var report = InboundReportParser.Parse(Bytes(raw));
        var r = Assert.Single(report.Recipients);
        static bool HasControl(string? s) => s is not null && s.Any(char.IsControl);
        Assert.False(HasControl(report.ReportingMta));
        Assert.False(HasControl(r.FinalRecipient));
        Assert.False(HasControl(r.OriginalRecipient));
        Assert.False(HasControl(r.Action));
        Assert.False(HasControl(r.RemoteMta));
        Assert.Equal("fa", r.Action);   // the action ends at the first blank, which the control character became
    }
}
