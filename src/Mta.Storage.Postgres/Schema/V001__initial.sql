-- EggMail PostgreSQL schema, version 1 (frozen: never edit, add V002 instead).
--
-- Generated once from the shared EF model (StorageModel.ConfigureAll + PostgresModelHooks) and then fixed in this file, so a
-- later model change cannot silently alter what a fresh database gets. A test compares every table and column of the
-- migrated database with the model. Conventions: snake_case names, no foreign keys (soft references), text columns use the
-- "C" collation (byte order, same as SQLite BINARY), timestamps are timestamptz, ids are uuid.
--
-- The five history tables are range partitioned by day (days since 1970-01-01 of the UUIDv7 message id) and start without
-- partitions; partitions are created ahead by the application (see PostgresPartitions). delivery_queue gets a lower
-- fillfactor and aggressive autovacuum settings because its rows are updated on every claim and attempt.

