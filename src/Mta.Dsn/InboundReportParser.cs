using System.Text;
using Mta.Mime;

namespace Mta.Dsn;

/// <summary>What an inbound message to the bounce domain turned out to be.</summary>
public enum InboundReportKind
{
    /// <summary>Not a machine-readable report (vacation reply, human reply, garbage).</summary>
    Unrecognized,

    /// <summary>RFC 3464 delivery status notification (multipart/report; report-type=delivery-status).</summary>
    DeliveryStatus,

    /// <summary>RFC 5965 abuse feedback report (multipart/report; report-type=feedback-report).</summary>
    FeedbackReport,
}

/// <summary>Per-recipient result extracted from a delivery status notification.</summary>
public sealed record InboundDsnRecipient(
    string? FinalRecipient,
    string? OriginalRecipient,
    string Action,
    string? Status,
    string? DiagnosticCode,
    string? RemoteMta,
    string? WillRetryUntil)
{
    /// <summary>True when the action is <c>failed</c> and the status class is 5 (permanent).</summary>
    public bool IsPermanentFailure => Action == "failed" && Status is { Length: > 0 } s && s[0] == '5';

    /// <summary>True when the action is <c>failed</c> and the status class is 4 (transient failure reported as final by the remote).</summary>
    public bool IsTransientFailure => Action == "failed" && Status is { Length: > 0 } s && s[0] == '4';

    /// <summary>True for <c>delayed</c> reports; these are informational and do not change delivery state.</summary>
    public bool IsDelay => Action == "delayed";
}

/// <summary>Result of parsing an inbound report. Everything is untrusted remote text; fields are bounded and control characters removed.</summary>
public sealed record InboundReport(
    InboundReportKind Kind,
    string? ReportingMta,
    IReadOnlyList<InboundDsnRecipient> Recipients,
    string? OriginalMessageId,
    string? FeedbackType,
    string? ArfOriginalRecipient,
    string? ArfSourceIp,
    bool IsAutoGenerated)
{
    /// <summary>Shared instance for anything that is not a recognised report.</summary>
    public static InboundReport None { get; } = new(InboundReportKind.Unrecognized, null, [], null, null, null, null, false);
}

/// <summary>
/// Parses inbound DSNs (RFC 3464) and ARF complaints (RFC 5965). Never throws on malformed input; limits keep the work bounded.
/// The parser does not decide who the report is about: the caller correlates through the VERP return path, not through
/// anything in the body, because the body is attacker-controlled.
/// </summary>
public static class InboundReportParser
{
    private const int MaxRecipients = 100;
    private const int MaxFieldChars = 1024;

    /// <summary>Parses a complete RFC 5322 message.</summary>
    public static InboundReport Parse(ReadOnlyMemory<byte> raw, MimeLimits? limits = null)
    {
        var message = MimeMessage.Parse(raw, limits);

        bool auto = IsAutoGenerated(message.Headers);
        var root = message.Root;
        if (!root.ContentType.Matches("multipart", "report"))
        {
            return InboundReport.None with { IsAutoGenerated = auto };
        }

        string? reportType = root.ContentType.Parameters["report-type"]?.Trim().ToLowerInvariant();
        return reportType switch
        {
            "delivery-status" => ParseDsn(root, auto),
            "feedback-report" => ParseArf(root, auto),
            _ => InboundReport.None with { IsAutoGenerated = auto },
        };
    }

    private static bool IsAutoGenerated(HeaderList headers)
    {
        string? autoSubmitted = headers.GetFirstValue("Auto-Submitted");
        return autoSubmitted is not null && !autoSubmitted.Trim().StartsWith("no", StringComparison.OrdinalIgnoreCase);
    }

    private static InboundReport ParseDsn(MimePart root, bool auto)
    {
        MimePart? status = null;
        string? originalMessageId = null;
        foreach (var part in root.Children)
        {
            if (part.ContentType.Matches("message", "delivery-status") || part.ContentType.Matches("message", "global-delivery-status"))
            {
                status ??= part;
            }
            else if (part.ContentType.Matches("message", "rfc822") || part.ContentType.Matches("text", "rfc822-headers") || part.ContentType.Matches("message", "global"))
            {
                originalMessageId ??= ExtractMessageId(part);
            }
        }

        if (status is null)
        {
            return InboundReport.None with { IsAutoGenerated = auto };
        }

        var groups = ParseFieldGroups(status.GetText(256 * 1024, out _));
        if (groups.Count == 0)
        {
            return InboundReport.None with { IsAutoGenerated = auto };
        }

        string? reportingMta = StripType(groups[0].GetValueOrDefault("reporting-mta"));
        var recipients = new List<InboundDsnRecipient>();
        for (int i = 1; i < groups.Count && recipients.Count < MaxRecipients; i++)
        {
            var g = groups[i];
            string? action = g.GetValueOrDefault("action")?.Trim().ToLowerInvariant();
            if (action is null)
            {
                continue;
            }

            int cut = action.IndexOf(' ');
            if (cut > 0)
            {
                action = action[..cut];
            }

            recipients.Add(new InboundDsnRecipient(
                StripType(g.GetValueOrDefault("final-recipient")),
                StripType(g.GetValueOrDefault("original-recipient")),
                action,
                NormalizeStatus(g.GetValueOrDefault("status")),
                Clean(StripType(g.GetValueOrDefault("diagnostic-code"))),
                StripType(g.GetValueOrDefault("remote-mta")),
                Clean(g.GetValueOrDefault("will-retry-until"))));
        }

        return new InboundReport(InboundReportKind.DeliveryStatus, reportingMta, recipients, originalMessageId, null, null, null, auto);
    }

    private static InboundReport ParseArf(MimePart root, bool auto)
    {
        MimePart? feedback = null;
        string? originalMessageId = null;
        foreach (var part in root.Children)
        {
            if (part.ContentType.Matches("message", "feedback-report"))
            {
                feedback ??= part;
            }
            else if (part.ContentType.Matches("message", "rfc822") || part.ContentType.Matches("text", "rfc822-headers"))
            {
                originalMessageId ??= ExtractMessageId(part);
            }
        }

        if (feedback is null)
        {
            return InboundReport.None with { IsAutoGenerated = auto };
        }

        var groups = ParseFieldGroups(feedback.GetText(64 * 1024, out _));
        if (groups.Count == 0)
        {
            return InboundReport.None with { IsAutoGenerated = auto };
        }

        var g = groups[0];
        return new InboundReport(
            InboundReportKind.FeedbackReport,
            null,
            [],
            originalMessageId ?? Clean(g.GetValueOrDefault("original-envelope-id")),
            Clean(g.GetValueOrDefault("feedback-type"))?.ToLowerInvariant(),
            Clean(g.GetValueOrDefault("original-rcpt-to")?.Trim('<', '>', ' ')),
            Clean(g.GetValueOrDefault("source-ip")),
            auto);
    }

    private static string? ExtractMessageId(MimePart part)
    {
        ReadOnlyMemory<byte> headerBytes;
        if (part.IsEmbeddedMessage && part.Children.Count == 1)
        {
            return Clean(part.Children[0].Headers.GetFirstValue(HeaderNames.MessageId)?.Trim());
        }

        headerBytes = part.Body;
        if (headerBytes.IsEmpty)
        {
            return null;
        }

        var headers = HeaderList.Parse(headerBytes);
        return Clean(headers.GetFirstValue(HeaderNames.MessageId)?.Trim());
    }

    /// <summary>Parses the "name: value" field groups separated by blank lines, honouring folded continuation lines.</summary>
    private static List<Dictionary<string, string>> ParseFieldGroups(string text)
    {
        var groups = new List<Dictionary<string, string>>();
        var current = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        string? lastName = null;
        foreach (string rawLine in text.Split('\n'))
        {
            string line = rawLine.TrimEnd('\r');
            if (line.Length == 0)
            {
                if (current.Count > 0)
                {
                    groups.Add(current);
                    current = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
                }

                lastName = null;
                continue;
            }

            if ((line[0] == ' ' || line[0] == '\t') && lastName is not null)
            {
                if (current[lastName].Length < MaxFieldChars)
                {
                    current[lastName] += " " + line.Trim();
                }

                continue;
            }

            int colon = line.IndexOf(':');
            if (colon <= 0)
            {
                lastName = null;
                continue;
            }

            string name = line[..colon].Trim();
            if (!current.ContainsKey(name))
            {
                current[name] = line[(colon + 1)..].Trim();
                lastName = name;
            }
            else
            {
                lastName = null;
            }
        }

        if (current.Count > 0)
        {
            groups.Add(current);
        }

        return groups;
    }

    /// <summary>Removes the "rfc822; " / "dns; " / "smtp; " type prefix of an address-type field.</summary>
    private static string? StripType(string? value)
    {
        if (value is null)
        {
            return null;
        }

        int semi = value.IndexOf(';');
        return semi >= 0 ? value[(semi + 1)..].Trim() : value.Trim();
    }

    private static string? NormalizeStatus(string? value)
    {
        string? s = Clean(value);
        if (s is null)
        {
            return null;
        }

        int cut = s.IndexOf(' ');
        if (cut > 0)
        {
            s = s[..cut];
        }

        // Enhanced status code: class.subject.detail, digits only.
        var parts = s.Split('.');
        if (parts.Length != 3 || parts.Any(p => p.Length is 0 or > 3 || !p.All(char.IsAsciiDigit)) || parts[0] is not ("2" or "4" or "5"))
        {
            return null;
        }

        return s;
    }

    private static string? Clean(string? value)
    {
        if (string.IsNullOrWhiteSpace(value))
        {
            return null;
        }

        var sb = new StringBuilder(Math.Min(value.Length, MaxFieldChars));
        foreach (char c in value)
        {
            if (sb.Length >= MaxFieldChars)
            {
                break;
            }

            sb.Append(char.IsControl(c) ? ' ' : c);
        }

        return sb.ToString().Trim();
    }
}
